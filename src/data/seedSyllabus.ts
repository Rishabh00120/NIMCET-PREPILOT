// Flat helper to extract all atomic trackable topics
export function getAllTrackableTopics(subjects: SyllabusSubject[]): SyllabusTopic[] {
  const topics: SyllabusTopic[] = [];
  for (const subject of subjects) {
    for (const chapter of subject.chapters) {
      for (const topic of chapter.topics) {
        topics.push(topic);
      }
    }
  }
  return topics;
}
